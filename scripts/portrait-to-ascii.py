#!/usr/bin/env python3
"""portrait.png -> ASCII art, emitted as a generated TypeScript module.

Two ramps in one pass, so the contacts page can swap between them with a
one-line import change:

  * CODE   - code glyphs. The "code-face" of the 07-22 spec; reads as source
             from a distance, which is the point on a BI/dev site.
  * BLOCKS - Unicode shading. Only five tonal levels, but each one is a solid
             fill, so it reads closest to a real grayscale photo.

Usage:

    python scripts/portrait-to-ascii.py
    python scripts/portrait-to-ascii.py --cols 120 --gamma 1.2
    python scripts/portrait-to-ascii.py --crop 300,250,1250,1650

Requires Pillow. Python 3.10 + PIL 9.5 confirmed on this machine (07-22 spec).

The output file is generated - do not hand-edit it. Re-run this instead.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageOps

# Ramps run LIGHTEST -> DARKEST. Index 0 must be a space: it is what the
# background of the photo collapses to, and it is also what makes the art
# cheap to gzip.
#
# Neither ramp may contain a backtick, a backslash, or a "{" - the art is
# emitted inside a TS template literal, and "$" is only safe here because no
# ramp contains "{", so the "${" interpolation sequence cannot form.
CODE_RAMP = " .,:-;=+*?%#&$@"
BLOCK_RAMP = " ░▒▓█"

# Width/height of one monospace cell at line-height 1. Geist Mono, like most
# monospace faces, advances 0.6em per character. The art is sampled at this
# ratio so the face is not stretched vertically when rendered as text; the CSS
# in ascii-portrait.module.css assumes the same 0.6 and must change with it.
CHAR_ASPECT = 0.6

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SRC = REPO / "article-src" / "service-page" / "portrait.png"
DEFAULT_OUT = REPO / "src" / "lib" / "ascii-portrait-art.ts"


def render(img: Image.Image, ramp: str, cols: int, gamma: float) -> str:
    """Resample to a character grid and map luminance onto `ramp`."""
    rows = max(1, round(img.height / img.width * cols * CHAR_ASPECT))
    small = img.resize((cols, rows), Image.LANCZOS)

    px = list(small.getdata())
    if gamma != 1.0:
        px = [round(255 * (p / 255) ** gamma) for p in px]

    last = len(ramp) - 1
    lines = []
    for r in range(rows):
        row = px[r * cols : (r + 1) * cols]
        # Invert: a dark pixel wants a dense glyph. The page is light-only
        # (no dark mode in globals.css), so this mapping never needs flipping.
        lines.append("".join(ramp[round((255 - p) / 255 * last)] for p in row))

    # Trailing spaces carry no ink and are pure payload.
    lines = [line.rstrip() for line in lines]

    # Blank rows at the top and bottom are not free: the CSS reserves one em of
    # height per row, so an empty row is a row of dead vertical space on the
    # page. Only the ends are trimmed — interior blanks are part of the image.
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()

    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--cols", type=int, default=110, help="output width in characters")
    ap.add_argument(
        "--crop",
        type=str,
        default=None,
        help="x,y,w,h in source pixels - crop before sampling (e.g. head and shoulders)",
    )
    ap.add_argument(
        "--gamma",
        type=float,
        default=1.0,
        help=">1 darkens midtones, <1 lightens them",
    )
    ap.add_argument(
        "--no-autocontrast",
        action="store_true",
        help="skip the full-tonal-range stretch",
    )
    args = ap.parse_args()

    if not args.src.exists():
        raise SystemExit(
            f"No portrait at {args.src}\n"
            "Save the source photo there first (front-facing, plain background)."
        )

    img = Image.open(args.src).convert("L")

    if args.crop:
        x, y, w, h = (int(v) for v in args.crop.split(","))
        img = img.crop((x, y, x + w, y + h))

    if not args.no_autocontrast:
        # A photo against a flat wall never spans 0-255; without this the ramp
        # only ever uses its middle and the face comes out washed out.
        img = ImageOps.autocontrast(img, cutoff=1)

    code = render(img, CODE_RAMP, args.cols, args.gamma)
    blocks = render(img, BLOCK_RAMP, args.cols, args.gamma)

    for name, art in (("CODE", code), ("BLOCKS", blocks)):
        if "`" in art or "\\" in art or "${" in art:
            raise SystemExit(f"{name} ramp produced a character unsafe in a template literal")

    rows = code.count("\n") + 1
    args.out.write_text(
        "// GENERATED by scripts/portrait-to-ascii.py - do not edit by hand.\n"
        f"// Source: {args.src.relative_to(REPO).as_posix()}\n"
        f"// Grid: {args.cols} cols x {rows} rows"
        f" | crop: {args.crop or 'none'} | gamma: {args.gamma}\n"
        "//\n"
        "// Two ramps so the page can swap without a regenerate; see\n"
        "// src/app/[locale]/contact/page.tsx for which one is live.\n\n"
        f"export const PORTRAIT_CODE = `{code}`;\n\n"
        f"export const PORTRAIT_BLOCKS = `{blocks}`;\n",
        encoding="utf-8",
        newline="\n",
    )

    print(f"{args.cols} cols x {rows} rows -> {args.out.relative_to(REPO).as_posix()}")
    print(f"  code:   {len(code):,} chars")
    print(f"  blocks: {len(blocks):,} chars")
    print("\n--- CODE preview ---\n")
    print(code)


if __name__ == "__main__":
    main()
